import gradio as gr

def chat_with_rag(
    message,
    history
):

    if not message.strip():
        return "", history

    try:

        result = rag_query(
            message,
            top_k=10,
            top_n=4
        )

        answer = result["answer"]

        pages = result["sources"]

        metrics = result["metrics"]

        # -----------------------------------------
        # Sources
        # -----------------------------------------

        if pages:

            source_text = (
                "\n\n### 📄 Sources\n"
                + ", ".join(
                    f"Page {page}"
                    for page in pages
                )
            )

        else:

            source_text = ""

        # -----------------------------------------
        # Performance
        # -----------------------------------------

        performance = f"""

---

### ⚡ Performance

| Stage | Time |
|---|---:|
| Query embedding | {metrics['query_embedding_latency']:.3f}s |
| Pinecone | {metrics['pinecone_latency']:.3f}s |
| Re-ranking | {metrics['reranking_latency']:.3f}s |
| Context building | {metrics['context_latency']:.3f}s |
| LLM generation | {metrics['llm_latency']:.3f}s |
| **Total** | **{metrics['total_latency']:.3f}s** |

Retrieved: `{metrics['retrieved_chunks']}` chunks
Reranked: `{metrics['reranked_chunks']}` chunks
"""

        final_answer = (
            answer
            + source_text
            + performance
        )

        history.append(
            {
                "role": "user",
                "content": message
            }
        )

        history.append(
            {
                "role": "assistant",
                "content": final_answer
            }
        )

        return "", history

    except Exception as e:

        logger.exception(
            "RAG_QUERY_FAILED"
        )

        history.append(
            {
                "role": "user",
                "content": message
            }
        )

        history.append(
            {
                "role": "assistant",
                "content": f"Error: {str(e)}"
            }
        )

        return "", history

