# recursive chunking strategy
def recursive_split_text(
    text,
    chunk_size=1000,
    chunk_overlap=150
):
    """
    Simple recursive text splitter.

    Separators are tried from strongest semantic boundary
    to weaker boundaries.
    """

    separators = [
        "\n\n",
        "\n",
        ". ",
        " ",
        ""
    ]

    def split_recursive(text, separators):

        if len(text) <= chunk_size:
            return [text]

        if not separators:
            return [
                text[i:i + chunk_size]
                for i in range(
                    0,
                    len(text),
                    chunk_size - chunk_overlap
                )
            ]

        separator = separators[0]

        parts = text.split(separator)

        chunks = []
        current = ""

        for part in parts:

            candidate = (
                current + separator + part
                if current
                else part
            )

            if len(candidate) <= chunk_size:
                current = candidate

            else:

                if current:
                    chunks.append(current.strip())

                current = part

        if current:
            chunks.append(current.strip())

        # If chunks are still too large, recursively split them
        final_chunks = []

        for chunk in chunks:

            if len(chunk) <= chunk_size:
                final_chunks.append(chunk)

            else:
                final_chunks.extend(
                    split_recursive(
                        chunk,
                        separators[1:]
                    )
                )

        return final_chunks

    raw_chunks = split_recursive(text, separators)

    # Add overlap
    final_chunks = []

    for i, chunk in enumerate(raw_chunks):

        if i > 0:

            previous = raw_chunks[i - 1]

            overlap_text = previous[
                max(0, len(previous) - chunk_overlap):
            ]

            chunk = overlap_text + " " + chunk

        final_chunks.append(chunk.strip())

    return final_chunks

# Create chunk objects
def create_chunks(documents):

    start_time = time.perf_counter()

    logger.info("CHUNKING_START")

    chunks = []

    chunk_counter = 0

    for doc in documents:

        page_chunks = recursive_split_text(
            doc["text"],
            chunk_size=CONFIG["chunk_size"],
            chunk_overlap=CONFIG["chunk_overlap"]
        )

        for page_chunk_index, chunk_text in enumerate(page_chunks):

            if len(chunk_text) < CONFIG["min_chunk_length"]:
                continue

            chunk_id = (
                f"{doc['document_id']}_"
                f"chunk_{chunk_counter:06d}"
            )

