# Reranking function
def rerank_documents(
    query,
    matches,
    top_n=4
):

    start_time = time.perf_counter()

    logger.info(
        f"RERANK_START | "
        f"candidates={len(matches)}"
    )

    if not matches:
        return []

    documents = []

    for match in matches:

        text = match.metadata.get(
            "text",
            ""
        )

        documents.append({
            "id": match.id,
            "pinecone_score": float(match.score),
            "page": match.metadata.get("page"),
            "source": match.metadata.get("source"),
            "text": text,
            "document_id": match.metadata.get(
                "document_id"
            ),
            "chunk_index": match.metadata.get(
                "chunk_index"
            )
        })

    # Query-document pairs
    pairs = [
        [query, document["text"]]
        for document in documents
    ]

    rerank_scores = reranker.predict(
        pairs,
        show_progress_bar=False
    )

    for document, score in zip(
        documents,
        rerank_scores
    ):
        document["rerank_score"] = float(score)

    # Highest relevance first
    documents.sort(
        key=lambda x: x["rerank_score"],
        reverse=True
    )

    final_documents = documents[:top_n]

    elapsed = (
        time.perf_counter() - start_time
    )

    logger.info(
        f"RERANK_COMPLETE | "
        f"returned={len(final_documents)} | "
        f"latency={elapsed:.4f}s"
    )

    return final_documents

