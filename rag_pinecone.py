# Wait until index is ready
def wait_for_index(pc, index_name, poll_interval=2):

    logger.info(
        f"PINECONE_INDEX_WAIT_START | "
        f"index={index_name}"
    )

    start_time = time.perf_counter()

    while True:

        description = pc.describe_index(
            index_name
        )

        status = description.status

        logger.info(
            f"PINECONE_INDEX_STATUS | "
            f"ready={status['ready']}"
        )

        if status["ready"]:
            break

        time.sleep(poll_interval)

    elapsed = time.perf_counter() - start_time

    logger.info(
        f"PINECONE_INDEX_READY | "
        f"latency={elapsed:.3f}s"
    )

