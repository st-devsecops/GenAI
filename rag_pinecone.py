def upsert_vectors(
    index,
    vectors,
    namespace,
    batch_size=100
):

    total_start = time.perf_counter()

    total_vectors = len(vectors)
    total_batches = (
        (total_vectors + batch_size - 1)
        // batch_size
    )

    logger.info(
        f"PINECONE_UPSERT_START | "
        f"vectors={total_vectors} | "
        f"batches={total_batches} | "
        f"batch_size={batch_size} | "
        f"namespace={namespace}"
    )

    uploaded = 0

    for batch_number, start in enumerate(
        range(0, total_vectors, batch_size),
        start=1
    ):

        batch = vectors[
            start:start + batch_size
        ]

        batch_start = time.perf_counter()

        logger.info(
            f"PINECONE_UPSERT_BATCH_START | "
            f"batch={batch_number}/{total_batches} | "
            f"size={len(batch)}"
        )

        index.upsert(
            vectors=batch,
            namespace=namespace
        )

        batch_elapsed = (
            time.perf_counter()
            - batch_start
        )

        uploaded += len(batch)

        logger.info(
            f"PINECONE_UPSERT_BATCH_COMPLETE | "
            f"batch={batch_number}/{total_batches} | "
            f"uploaded={uploaded}/{total_vectors} | "
            f"latency={batch_elapsed:.3f}s"
        )

    total_elapsed = (
        time.perf_counter()
        - total_start
    )

    logger.info(
        f"PINECONE_UPSERT_COMPLETE | "
        f"vectors={uploaded} | "
        f"latency={total_elapsed:.3f}s"
    )

    return {
        "vectors_uploaded": uploaded,
        "total_batches": total_batches,
        "latency_seconds": total_elapsed
    }

