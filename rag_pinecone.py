# Validate vectors before uploading
def validate_pinecone_vectors(vectors, expected_dimension):

    logger.info(
        f"PINECONE_VECTOR_VALIDATION_START | "
        f"vectors={len(vectors)}"
    )

    if not vectors:
        raise ValueError("No vectors to upload")

    ids = set()

    for vector in vectors:

        # Check ID
        if not vector["id"]:
            raise ValueError("Vector has empty ID")

        # Check duplicate ID
        if vector["id"] in ids:
            raise ValueError(
                f"Duplicate vector ID: {vector['id']}"
            )

        ids.add(vector["id"])

        # Check dimensions
        if len(vector["values"]) != expected_dimension:
            raise ValueError(
                f"Invalid dimension for "
                f"{vector['id']}: "
                f"{len(vector['values'])}"
            )

        # Check metadata
        if not vector["metadata"].get("text"):
            raise ValueError(
                f"Missing text metadata: {vector['id']}"
            )

    logger.info(
        f"PINECONE_VECTOR_VALIDATION_PASSED | "
        f"vectors={len(vectors)} | "
        f"dimension={expected_dimension}"
    )

