# Local llm generation
def generate_answer(
    question,
    context,
    max_new_tokens=300
):

    start_time = time.perf_counter()

    logger.info("LLM_GENERATION_START")

    messages = build_rag_messages(
        question,
        context
    )

    # ---------------------------------------------
    # Apply Qwen chat template
    # ---------------------------------------------

    prompt = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True
    )

    # ---------------------------------------------
    # Tokenize
    # ---------------------------------------------

    inputs = tokenizer(
        prompt,
        return_tensors="pt"
    )

    inputs = {
        key: value.to(model.device)
        for key, value in inputs.items()
    }

    input_tokens = (
        inputs["input_ids"].shape[1]
    )

    # ---------------------------------------------
    # Generate
    # ---------------------------------------------

    with torch.no_grad():

        outputs = model.generate(
            **inputs,

            max_new_tokens=max_new_tokens,

            temperature=0.2,

            do_sample=True,

            top_p=0.9,

            repetition_penalty=1.05
        )

    # ---------------------------------------------
    # Extract only generated answer
    # ---------------------------------------------

    generated_tokens = outputs[
        0,
        input_tokens:
    ]

    answer = tokenizer.decode(
        generated_tokens,
        skip_special_tokens=True
    ).strip()

    elapsed = (
        time.perf_counter() - start_time
    )

    output_tokens = len(
        generated_tokens
    )

    logger.info(
        f"LLM_GENERATION_COMPLETE | "
        f"input_tokens={input_tokens} | "
        f"output_tokens={output_tokens} | "
        f"latency={elapsed:.3f}s"
    )

    return {
        "answer": answer,
        "latency": elapsed,
        "input_tokens": input_tokens,
        "output_tokens": output_tokens
    }

def rag_query(
    question,
    top_k=10,
    top_n=4
):

    total_start = time.perf_counter()

    logger.info("")
    logger.info("=" * 80)
    logger.info("RAG_QUERY_START")
    logger.info(f"Question: {question}")
    logger.info("=" * 80)

    # ==================================================
    # 1. RETRIEVAL
    # ==================================================

    retrieval = retrieve_documents(
        question,
        top_k=top_k
    )

    matches = retrieval["matches"]

    # ==================================================
    # 2. RERANKING
    # ==================================================

    rerank_start = time.perf_counter()

    reranked_docs = rerank_documents(
        question,
        matches,
        top_n=top_n
    )

    rerank_latency = (
        time.perf_counter()
        - rerank_start
    )

    # ==================================================
    # 3. CONTEXT
    # ==================================================

    context_start = time.perf_counter()

    context = build_context(
        reranked_docs
    )

    context_latency = (
        time.perf_counter()
        - context_start
    )

    # ==================================================
    # 4. LLM
    # ==================================================

    llm_result = generate_answer(
        question,
        context
    )

    # ==================================================
    # 5. TOTAL
    # ==================================================

    total_latency = (
        time.perf_counter()
        - total_start
    )

    # ==================================================
    # 6. SOURCES
    # ==================================================

    sources = sorted(
        set(
            doc["page"]
            for doc in reranked_docs
        )
    )

    metrics = {

        "query_embedding_latency":
            retrieval["embedding_latency"],

        "pinecone_latency":
            retrieval["search_latency"],

        "reranking_latency":
            rerank_latency,

        "context_latency":
            context_latency,

        "llm_latency":
            llm_result["latency"],

        "total_latency":
            total_latency,

        "retrieved_chunks":
            len(matches),

        "reranked_chunks":
            len(reranked_docs),

        "input_tokens":
            llm_result["input_tokens"],

        "output_tokens":
            llm_result["output_tokens"],

        "sources":
            sources
    }

    logger.info(
        f"RAG_QUERY_COMPLETE | "
        f"total_latency={total_latency:.3f}s"
    )

    return {
        "answer": llm_result["answer"],
        "sources": sources,
        "documents": reranked_docs,
        "context": context,
        "metrics": metrics
    }

